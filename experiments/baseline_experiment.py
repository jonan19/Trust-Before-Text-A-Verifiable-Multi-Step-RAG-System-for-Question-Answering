"""
baseline_experiment.py — Prompted-LLM baseline for the "Trust Before Text" paper.

Purpose
-------
Compare our deterministic RAG gate against a STRONG prompted-LLM baseline on the
three axes where soft prompting is known to break (see MASTER_PROMPT / Journal
Guide §4.5):

    Pillar 1  Determinism / consistency  — does the baseline flip across reruns?
    Pillar 2  Parametric leakage         — does it invent answers on gap queries?
    Pillar 3  Conflict-attribution       — does it flag + name docs + give values?

Plus an honest straight-accuracy comparison (Part E).

Design
------
* We do NOT touch validation.py / orchestrator.py or any threshold. This script
  only READS the frozen system's decisions (data/phase6_fullrun_results.json) and
  reproduces the retrieval our system sees, then calls a real LLM.
* The baseline gets the SAME retrieved evidence our system sees:
      preprocess_query -> classify_query -> decompose_query (if complex)
      -> retrieve_for_queries  (with the orchestrator's dynamic top_k)
* Each query is called 6x: 1x at temp 0.0 (canonical decision -> Parts D & E)
  and 5x at temp 0.7 (consistency -> Part B). Part C leakage is read from the
  16 gap queries within the same runs (no extra calls).

Usage
-----
  python experiments/baseline_experiment.py --smoke        # 5-query smoke test
  python experiments/baseline_experiment.py --all          # full 78-query run
  python experiments/baseline_experiment.py --ids Q001,Q035 --runs 5 --temp 0.7

Environment
-----------
  Requires GROQ_API_KEY in .env (Groq llama-3.3-70b-versatile).
  Set HF_HUB_DISABLE_PROGRESS_BARS=1 TRANSFORMERS_VERBOSITY=error to quiet HF.
"""

