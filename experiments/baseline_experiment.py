# ---------------------------------------------------------------------------
# Baseline prompt (exact shape from the master prompt / Journal Guide §4.5)
# ---------------------------------------------------------------------------
BASELINE_SYSTEM = (
    "You answer questions using ONLY the provided context passages. "
    "Follow these rules exactly:\n"
    "1. If the answer is not present in the context, reply with exactly the single "
    "word: INSUFFICIENT\n"
    "2. If two passages give conflicting values for the fact being asked, reply with "
    "the word CONFLICT followed by both values and which document each value came from.\n"
    "3. Otherwise, give the answer, citing the document it came from.\n"
    "Do not use any knowledge beyond the context passages."
)

BASELINE_USER_TMPL = (
    "Context passages:\n{chunks}\n\n"
    "Question: {query}\n\n"
    "Answer (remember: exactly INSUFFICIENT if not present; start with CONFLICT if "
    "two passages disagree on the asked fact):"
)


# ---------------------------------------------------------------------------
# Retrieval reproduction — mirrors orchestrator.run's non-source-targeted path
# ---------------------------------------------------------------------------
def retrieve_same_evidence(raw_query: str) -> tuple[list[dict], list[str], str]:
    """Return (chunks, sub_queries, query_type) exactly as the orchestrator sees.

    None of the 78 HR queries name a document file, so the orchestrator's
    source-targeting branch never fires here; the normal semantic path applies.
    """
    pq = preprocess_query(raw_query)
    qtype = classify_query(pq)
    subs = decompose_query(pq) if qtype == "complex" else [pq]
    top_k = (
        RETRIEVAL_TOP_K + len(subs)
        if qtype == "complex" and len(subs) > 1
        else RETRIEVAL_TOP_K
    )
    chunks = retrieve_for_queries(subs, top_k=top_k)
    return chunks, subs, qtype


def build_context_block(chunks: list[dict], max_chunks: int | None = None) -> str:
    """Number each passage and label it with its source document filename so the
    baseline can (a) reason from it and (b) name the source in conflict cases.

    Chunks arrive ranked by descending retrieval score. `max_chunks` caps how
    many are sent to the LLM (token budget); None = send all. Capping to the
    top-N retrieved passages preserves recall (our validation stage keeps far
    fewer than N relevant) while bounding tokens-per-call.
    """
    if not chunks:
        return "(no passages retrieved)"
    if max_chunks is not None:
        chunks = chunks[:max_chunks]
    lines = []
    for i, c in enumerate(chunks, 1):
        src = c.get("source", "unknown")
        text = (c.get("text", "") or "").strip()
        lines.append(f"[Passage {i} | Source: {src}]\n{text}")
    return "\n\n".join(lines)


# ---------------------------------------------------------------------------
# Groq call with rate-limit-aware retry
# ---------------------------------------------------------------------------
class DailyTokenExhausted(Exception):
    """Raised only when EVERY configured Groq key is unavailable for the rest of
    today — either it hit its tokens-per-day (TPD) cap or it is permanently
    unusable (e.g. the model is blocked at that key's org level). The caller
    should checkpoint and stop."""


# ── Multi-key rotation state ────────────────────────────────────────────────
# Each free Groq key carries its own 100k tokens/day cap. We rotate across all
# keys set in the environment (GROQ_API_KEY, GROQ_API_KEY_2, GROQ_API_KEY_3,
# ...). When a key returns a TPD 429 we mark it exhausted for the session and
# move to the next; we only give up when all keys are exhausted.
_GROQ_KEYS: list[str] = []
_GROQ_CLIENTS: dict[int, object] = {}
_EXHAUSTED: set[int] = set()
_CUR_KEY = 0


def _load_keys() -> list[str]:
    """Collect all non-empty Groq keys from the environment, in order."""
    keys: list[str] = []
    primary = os.getenv("GROQ_API_KEY", "").strip()
    if primary:
        keys.append(primary)
    i = 2
    while True:
        k = os.getenv(f"GROQ_API_KEY_{i}", "").strip()
        if k:
            keys.append(k)
            i += 1
        elif i <= 3:
            # allow a gap (e.g. _2 blank but _3 set) up to _3
            i += 1
        else:
            break
    # de-dup while preserving order
    seen, out = set(), []
    for k in keys:
        if k not in seen:
            seen.add(k)
            out.append(k)
    return out


def _init_keys() -> None:
    global _GROQ_KEYS
    if not _GROQ_KEYS:
        _GROQ_KEYS = _load_keys()
        if not _GROQ_KEYS:
            raise RuntimeError("No GROQ_API_KEY* set in environment/.env")


def _client(idx: int):
    if idx not in _GROQ_CLIENTS:
        from groq import Groq
        _GROQ_CLIENTS[idx] = Groq(api_key=_GROQ_KEYS[idx])
    return _GROQ_CLIENTS[idx]


def n_keys() -> int:
    _init_keys()
    return len(_GROQ_KEYS)


def _advance_key() -> bool:
    """Move to the next non-exhausted key. Return False if none remain."""
    global _CUR_KEY
    for _ in range(len(_GROQ_KEYS)):
        _CUR_KEY = (_CUR_KEY + 1) % len(_GROQ_KEYS)
        if _CUR_KEY not in _EXHAUSTED:
            return True
    return False


def groq_chat(system_prompt: str, user_message: str, temperature: float,
              max_retries: int = 5) -> str:
    """General rotating Groq chat call (system + user). Shares the multi-key
    rotation / daily-cap handling used by call_baseline, so any experiment
    (injection defense prompts, our synthesis, etc.) can reuse it."""
    _init_keys()
    global _CUR_KEY
    if _CUR_KEY in _EXHAUSTED and not _advance_key():
        raise DailyTokenExhausted("all Groq keys exhausted")

    delay = 2.0
    last = None
    attempt = 0
    while attempt < max_retries:
        try:
            resp = _client(_CUR_KEY).chat.completions.create(
                model=GROQ_MODEL,
                messages=[
                    {"role": "system", "content": system_prompt},
                    {"role": "user", "content": user_message},
                ],
                temperature=temperature,
                max_tokens=512,
            )
            return resp.choices[0].message.content.strip()
        except Exception as exc:
            last = exc
            msg = str(exc).lower()
            if "tokens per day" in msg or "tpd" in msg:
                _EXHAUSTED.add(_CUR_KEY)
                print(f"    [key {_CUR_KEY + 1}/{len(_GROQ_KEYS)} hit daily cap; "
                      f"rotating]", flush=True)
                if _advance_key():
                    continue
                raise DailyTokenExhausted(str(exc)) from exc
            if ("permission" in msg or "blocked" in msg or "403" in msg
                    or "model_permission" in msg):
                _EXHAUSTED.add(_CUR_KEY)
                print(f"    [key {_CUR_KEY + 1}/{len(_GROQ_KEYS)} unusable; skipping]",
                      flush=True)
                if _advance_key():
                    continue
                raise DailyTokenExhausted(str(exc)) from exc
            wait = delay
            m = re.search(r"try again in ([0-9.]+)s", msg)
            if m:
                wait = float(m.group(1)) + 0.5
            attempt += 1
            if attempt < max_retries:
                time.sleep(wait)
                delay *= 2
    raise RuntimeError(f"Groq call failed after {max_retries} attempts: {last}")


def call_baseline(context: str, query: str, temperature: float,
                  max_retries: int = 5) -> str:
    _init_keys()
    global _CUR_KEY
    # ensure current key is usable
    if _CUR_KEY in _EXHAUSTED and not _advance_key():
        raise DailyTokenExhausted("all Groq keys exhausted")

    user = BASELINE_USER_TMPL.format(chunks=context, query=query)
    delay = 2.0
    last = None
    attempt = 0
    while attempt < max_retries:
        try:
            resp = _client(_CUR_KEY).chat.completions.create(
                model=GROQ_MODEL,
                messages=[
                    {"role": "system", "content": BASELINE_SYSTEM},
                    {"role": "user", "content": user},
                ],
                temperature=temperature,
                max_tokens=512,
            )
            return resp.choices[0].message.content.strip()
        except Exception as exc:  # rate limit / transient
            last = exc
            msg = str(exc).lower()
            # tokens-per-day cap for THIS key → mark exhausted, switch keys.
            if "tokens per day" in msg or "tpd" in msg:
                _EXHAUSTED.add(_CUR_KEY)
                print(f"    [key {_CUR_KEY + 1}/{len(_GROQ_KEYS)} hit daily cap; "
                      f"rotating]", flush=True)
                if _advance_key():
                    continue  # retry same call on the next key (no attempt cost)
                raise DailyTokenExhausted(str(exc)) from exc
            # permission / model-blocked for THIS key → permanently unusable
            # today (org hasn't enabled the model). Skip it, don't retry.
            if ("permission" in msg or "blocked" in msg or "403" in msg
                    or "model_permission" in msg):
                _EXHAUSTED.add(_CUR_KEY)
                print(f"    [key {_CUR_KEY + 1}/{len(_GROQ_KEYS)} unusable "
                      f"(model blocked at org level); skipping]", flush=True)
                if _advance_key():
                    continue
                raise DailyTokenExhausted(str(exc)) from exc
            # per-minute rate limit or transient → wait and retry same key
            wait = delay
            m = re.search(r"try again in ([0-9.]+)s", msg)
            if m:
                wait = float(m.group(1)) + 0.5
            attempt += 1
            if attempt < max_retries:
                time.sleep(wait)
                delay *= 2
    raise RuntimeError(f"Groq call failed after {max_retries} attempts: {last}")


# ---------------------------------------------------------------------------
# Parse the baseline reply into a decision
# ---------------------------------------------------------------------------
def parse_decision(reply: str) -> str:
    """Map a raw reply to answer / conflict / insufficient."""
    head = reply.strip().upper()
    # strip leading markdown / quotes
    head = head.lstrip("*_`\"' \n\t")
    first = head[:40]
    if first.startswith("CONFLICT"):
        return "conflict"
    if first.startswith("INSUFFICIENT"):
        return "insufficient"
    # defensive: some models wrap the keyword
    if re.match(r"^(THE ANSWER IS )?CONFLICT\b", first):
        return "conflict"
    if re.match(r"^(THE ANSWER IS )?INSUFFICIENT\b", first):
        return "insufficient"
    return "answer"


# ---------------------------------------------------------------------------
# Part D grading key: conflict doc pair -> {docA:(val tokens), docB:(val tokens)}
# ---------------------------------------------------------------------------
def build_conflict_key(gt: dict) -> dict:
    """frozenset(docA, docB) -> {'docs':[a,b], 'values':{a:[toks], b:[toks]}}"""
    key = {}
    for c in gt.get("conflicts", []):
        docs = c["docs"]  # [[file, value, section], ...]
        (fa, va, _), (fb, vb, _) = docs[0], docs[1]
        key[frozenset((fa, fb))] = {
            "docs": [fa, fb],
            "values": {fa: _value_tokens(va), fb: _value_tokens(vb)},
        }
    return key


def _value_tokens(value_str: str) -> list[str]:
    """Distinctive tokens that must appear for a value to count as 'given'.
    e.g. '3 months' -> ['3'], '6%' -> ['6'], 'permitted...' -> ['permit'].
    """
    v = value_str.lower()
    nums = re.findall(r"\d+", v)
    if nums:
        return [nums[0]]
    # non-numeric stance conflicts (device permitted vs prohibited)
    for stem in ("permit", "prohibit", "allow", "forbid", "ban", "not permit"):
        if stem in v:
            return [stem]
    return [v.split()[0]] if v.split() else []


def _doc_named(reply: str, doc_file: str) -> bool:
    """Did the reply name this document (by filename stem tokens)?"""
    stem = Path(doc_file).stem.lower().replace("_", " ")
    reply_l = reply.lower()
    if stem in reply_l:
        return True
    # require the distinctive content words of the title to be present
    stop = {"and", "the", "of", "policy", "2023", "superseded", "mgt", "hr"}
    words = [w for w in re.split(r"[\s_]+", stem) if w and w not in stop]
    if not words:
        return False
    return all(w in reply_l for w in words)


def grade_attribution(reply: str, decision: str, pair: list[str],
                      conflict_key: dict) -> dict:
    """3-point grade on a conflict query: flagged / named both docs / both values."""
    flagged = decision == "conflict"
    entry = conflict_key.get(frozenset(pair))
    named_both = False
    both_values = False
    if entry:
        a, b = entry["docs"]
        named_both = _doc_named(reply, a) and _doc_named(reply, b)
        rl = reply.lower()
        va_ok = all(t in rl for t in entry["values"][a])
        vb_ok = all(t in rl for t in entry["values"][b])
        both_values = va_ok and vb_ok
    return {
        "flagged_conflict": flagged,
        "named_both_docs": named_both,
        "gave_both_values": both_values,
        "score": int(flagged) + int(named_both) + int(both_values),
    }


# ---------------------------------------------------------------------------
# Contains-a-concrete-answer test for leakage (Part C)
# ---------------------------------------------------------------------------
def is_concrete_answer(decision: str) -> bool:
    """On a gap query, a non-INSUFFICIENT (and non-CONFLICT) reply = leakage."""
    return decision == "answer"


# ---------------------------------------------------------------------------
# Main experiment
# ---------------------------------------------------------------------------
def load_frozen_ours() -> dict:
    if not FROZEN_PATH.exists():
        raise RuntimeError(
            f"{FROZEN_PATH} not found. Run `python experiments/our_decisions.py` "
            "first to generate the current-system decisions (zero LLM tokens)."
        )
    payload = json.load(open(FROZEN_PATH, encoding="utf-8"))
    recs = payload["results"] if isinstance(payload, dict) else payload
    return {r["id"]: r for r in recs}


def run_experiment(query_ids: list[str] | None, n_hot_runs: int, hot_temp: float,
                   max_chunks: int | None, checkpoint_path: Path | None):
    queries = json.load(open(QUERIES_PATH, encoding="utf-8"))["queries"]
    gt = json.load(open(GT_PATH, encoding="utf-8"))
    conflict_key = build_conflict_key(gt)
    ours = load_frozen_ours()

    if query_ids:
        queries = [q for q in queries if q["id"] in query_ids]

    # ── Resume: load already-completed query records from the checkpoint ──
    results: list[dict] = []
    done_ids: set[str] = set()
    if checkpoint_path and checkpoint_path.exists():
        try:
            prev = json.load(open(checkpoint_path, encoding="utf-8"))
            results = prev.get("results", [])
            done_ids = {r["id"] for r in results}
            if done_ids:
                print(f"Resuming: {len(done_ids)} queries already done, skipping "
                      f"them.\n", flush=True)
        except Exception:
            pass

    def _save_checkpoint():
        if checkpoint_path is None:
            return
        json.dump({"results": results}, open(checkpoint_path, "w", encoding="utf-8"),
                  indent=2)

    n = len(queries)
    stopped_early = False
    for idx, q in enumerate(queries, 1):
        qid = q["id"]
        if qid in done_ids:
            continue
        raw = q["query"]
        expected = q["expected_decision"]
        pair = q.get("expected_conflict_pair")

        chunks, subs, qtype = retrieve_same_evidence(raw)
        context = build_context_block(chunks, max_chunks=max_chunks)
        sources = sorted({c.get("source", "unknown") for c in chunks})
        n_sent = len(chunks) if max_chunks is None else min(max_chunks, len(chunks))

        print(f"[{idx}/{n}] {qid} ({expected}) — {len(chunks)} chunks "
              f"(sent {n_sent}), type={qtype}", flush=True)

        try:
            # 1x canonical @ temp 0.0
            canon_reply = call_baseline(context, raw, temperature=0.0)
            canon_dec = parse_decision(canon_reply)

            # N x @ hot_temp for consistency
            hot_replies, hot_decs = [], []
            for r in range(n_hot_runs):
                rep = call_baseline(context, raw, temperature=hot_temp)
                hot_replies.append(rep)
                hot_decs.append(parse_decision(rep))
        except DailyTokenExhausted as exc:
            print(f"\n[!] Groq daily token cap hit on {qid}. Saving "
                  f"{len(results)} completed queries and stopping.\n    {exc}",
                  flush=True)
            _save_checkpoint()
            stopped_early = True
            break

        inconsistent = len(set(hot_decs)) > 1  # flips across the hot runs

        rec = {
            "id": qid,
            "category": q.get("category"),
            "query": raw,
            "expected": expected,
            "expected_conflict_pair": pair,
            "n_chunks": len(chunks),
            "n_chunks_sent": n_sent,
            "retrieved_sources": sources,
            "sub_queries": subs,
            "query_type": qtype,
            # our (frozen) system
            "ours_decision": ours.get(qid, {}).get("observed"),
            "ours_conflict_pair": ours.get(qid, {}).get("conflict_pair"),
            # baseline
            "baseline_canonical_decision": canon_dec,
            "baseline_canonical_reply": canon_reply,
            "baseline_hot_decisions": hot_decs,
            "baseline_hot_temp": hot_temp,
            "baseline_inconsistent": inconsistent,
        }

        # Part C — leakage (gap queries only)
        if expected == "insufficient":
            rec["leakage"] = {
                "canonical_leaked": is_concrete_answer(canon_dec),
                "hot_leak_count": sum(is_concrete_answer(d) for d in hot_decs),
                "hot_runs": n_hot_runs,
            }

        # Part D — attribution (conflict queries only), graded on canonical reply
        if expected == "conflict" and pair:
            rec["attribution"] = grade_attribution(
                canon_reply, canon_dec, pair, conflict_key
            )

        results.append(rec)
        _save_checkpoint()   # checkpoint after every completed query

    return results, stopped_early


def summarize(results: list[dict]) -> dict:
    n = len(results)
    ours_correct = sum(1 for r in results if r["ours_decision"] == r["expected"])
    base_correct = sum(
        1 for r in results if r["baseline_canonical_decision"] == r["expected"]
    )
    # Pillar 1: consistency
    flips = sum(1 for r in results if r["baseline_inconsistent"])
    # Pillar 2: leakage on gaps
    gaps = [r for r in results if r["expected"] == "insufficient"]
    gap_leaks_canon = sum(1 for r in gaps if r["leakage"]["canonical_leaked"])
    gap_leak_any_hot = sum(
        1 for r in gaps if r["leakage"]["hot_leak_count"] > 0
    )
    ours_gap_leaks = sum(
        1 for r in gaps if r["ours_decision"] == "answer"
    )
    # Pillar 3: attribution on conflicts
    confs = [r for r in results if r["expected"] == "conflict"]
    attr_scores = [r["attribution"]["score"] for r in confs] if confs else []
    base_flagged = sum(1 for r in confs if r["attribution"]["flagged_conflict"])
    base_named = sum(1 for r in confs if r["attribution"]["named_both_docs"])
    base_values = sum(1 for r in confs if r["attribution"]["gave_both_values"])
    ours_conf_correct = sum(1 for r in confs if r["ours_decision"] == "conflict")

    return {
        "n_queries": n,
        "accuracy": {
            "ours": ours_correct, "ours_pct": round(100 * ours_correct / n, 1),
            "baseline": base_correct, "baseline_pct": round(100 * base_correct / n, 1),
        },
        "pillar1_consistency": {
            "baseline_flips": flips,
            "baseline_flip_pct": round(100 * flips / n, 1),
            "ours_flips": 0,
            "note": "flip = the 5 temp>0 runs are not all identical",
        },
        "pillar2_leakage": {
            "n_gaps": len(gaps),
            "baseline_canonical_leaks": gap_leaks_canon,
            "baseline_any_hot_leaks": gap_leak_any_hot,
            "ours_leaks": ours_gap_leaks,
        },
        "pillar3_attribution": {
            "n_conflicts": len(confs),
            "baseline_flagged": base_flagged,
            "baseline_named_both_docs": base_named,
            "baseline_gave_both_values": base_values,
            "baseline_mean_score_out_of_3": (
                round(sum(attr_scores) / len(attr_scores), 2) if attr_scores else None
            ),
            "ours_flagged": ours_conf_correct,
            "ours_structural_score_out_of_3": 3,
            "note": "ours names both docs + quotes both sentences structurally",
        },
    }


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--smoke", action="store_true",
                    help="5-query smoke test (2 answer, 2 conflict, 1 gap)")
    ap.add_argument("--all", action="store_true", help="full 78-query run")
    ap.add_argument("--ids", type=str, default="",
                    help="comma-separated query ids")
    ap.add_argument("--runs", type=int, default=5,
                    help="number of temp>0 consistency runs per query")
    ap.add_argument("--temp", type=float, default=0.7,
                    help="temperature for consistency runs")
    ap.add_argument("--max-chunks", type=int, default=12,
                    help="cap passages sent to the LLM per call (token budget); "
                         "0 = send all retrieved")
    ap.add_argument("--out", type=str, default="",
                    help="output json filename (under experiments/); also the "
                         "resume checkpoint — re-run the same command to continue")
    args = ap.parse_args()

    if args.smoke:
        ids = ["Q005", "Q010", "Q035", "Q042", "Q049"]
        out_name = args.out or "baseline_results_smoke.json"
    elif args.all:
        ids = None
        out_name = args.out or "baseline_results.json"
    elif args.ids:
        ids = [x.strip() for x in args.ids.split(",") if x.strip()]
        out_name = args.out or "baseline_results_custom.json"
    else:
        ap.error("specify --smoke, --all, or --ids")

    max_chunks = None if args.max_chunks == 0 else args.max_chunks
    checkpoint_path = OUT / out_name

    print(f"Model  : {GROQ_MODEL}  |  consistency runs: {args.runs} @ temp {args.temp}")
    print(f"Groq keys detected: {n_keys()} (rotating; ~{100 * n_keys()}k tokens/day)")
    print(f"Context cap: {max_chunks if max_chunks else 'all'} passages/call")
    n_q = len(ids) if ids else 78
    calls = n_q * (1 + args.runs)
    print(f"Planned Groq calls (if none done yet): {calls}")
    print(f"Checkpoint/out: {checkpoint_path}  (re-run same command to resume)\n")

    t0 = time.time()
    results, stopped_early = run_experiment(
        ids, args.runs, args.temp, max_chunks, checkpoint_path
    )
    summary = summarize(results)
    elapsed = time.time() - t0

    payload = {
        "meta": {
            "model": GROQ_MODEL,
            "consistency_runs": args.runs,
            "consistency_temp": args.temp,
            "canonical_temp": 0.0,
            "max_chunks_sent": max_chunks,
            "n_queries": len(results),
            "elapsed_sec": round(elapsed, 1),
            "stopped_early_daily_cap": stopped_early,
        },
        "summary": summary,
        "results": results,
    }
    json.dump(payload, open(checkpoint_path, "w", encoding="utf-8"), indent=2)

    print("\n" + "=" * 60)
    print("SUMMARY" + ("  (PARTIAL — daily token cap hit)" if stopped_early else ""))
    print("=" * 60)
    print(json.dumps(summary, indent=2))
    print(f"\nWrote {checkpoint_path}  ({elapsed:.0f}s, {len(results)} queries done)")
    if stopped_early:
        print("Daily token cap reached — re-run the SAME command after the cap "
              "resets (~24h) to continue where it stopped.")


if __name__ == "__main__":
    main()
